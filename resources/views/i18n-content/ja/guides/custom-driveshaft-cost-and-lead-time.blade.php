<h2 id="lead">納期</h2>
<p>カスタム注文では、3つの時間が進行します。<strong>確認:</strong>お客様の寸法とヨークの選択を車両に照らして確認します。数値がそろっていれば当日中に完了しますが、ご質問が必要な場合はお時間をいただきます。<a href="/guides/how-to-measure-a-driveshaft">採寸ガイド</a>をご覧いただくと、この工程を一度で済ませることができます。<strong>製作:</strong>ヨークが在庫にあるスチール製1ピースのプロペラシャフトは、通常、カット、溶接、矯正、バランス取り、塗装まで営業日で数日で完了します。アルミ製や2ピースのものはさらに時間がかかり、在庫にないヨークが必要な場合は、そのヨークの入荷をお待ちいただきます。<strong>発送:</strong>フロリダからの陸送で、米国東部の大部分には2~3日、西海岸には5日で到着します。近隣のお客様は店舗での受け取りも可能です。納期にご希望がある場合は、ご注文前に(813) 524-6491までお電話ください。間に合うかどうか、正直にお答えします。</p>

<h2 id="premade">既製品のほうが安くなる場合</h2>
<p>車両がノーマルまたはほぼノーマルであれば、純正の長さの<a href="/shop/complete-driveshafts">完成品プロペラシャフト</a>のほうがカスタムより安く、当日出荷も可能です。まず<a href="/catalog/driveshafts">車種別検索</a>をご確認ください。カスタムの価値が出てくるのは、車両がリフトアップまたはローダウンされている場合、トランスミッションやアクスルを交換している場合、ホイールベースが標準と異なる場合、あるいは純正のプロペラシャフトが想定していない使い方をする場合です。古いプロペラシャフトが、ユニバーサルジョイントやベアリングの摩耗以外は問題ない状態であれば、修理がどちらの選択肢よりも安く済みます。その判断には<a href="/guides/replace-or-repair-a-driveshaft">修理か交換かのガイド</a>をご活用ください。</p>