<p>カスタムプロペラシャフトの見積もりは、いくつかの決定事項から成り立っており、それぞれがいくら加算されるかが分かれば、想定外の金額が出ることはありません。このガイドでは、価格を左右する要素、金額に含まれるもの、当店カタログの実際の部品価格(お金がどこにかかっているかがお分かりいただけます)、そして目安となる納期を説明します。<a href="/online-builder">プロペラシャフトをオーダー</a>では、これらの計算をリアルタイムで行います。使用用途、シリーズ、素材、ヨークを選び、寸法を入力すると、バランス取りまで完了した完成品のプロペラシャフトの価格が画面に表示されます。</p>

<h2 id="drivers">価格を決める5つの要素</h2>
<ol class="guide-steps">
<li><strong>シリーズ。</strong>ユニバーサルジョイントのシリーズによって、各ヨークとジョイントのサイズが決まります。1310と1330の部品は最も安価で流通量も豊富です。1350は少し高くなります。1410、1480、1550は鍛造部品が大きく、ヨークの種類も少ないため、さらに高くなります。強度の問題を解決する場合を除き、車両にすでに使われているシリーズを選んでください。</li>
<li><strong>素材。</strong>DOMスチールチューブが基本です。アルミチューブは1フィートあたりの価格が高く、アルミ専用のウェルドヨークが必要で、溶接にもより慎重な作業が求められます。同じ長さでもかなりの割増になるとお考えください。どのような場合に採用する価値があるかは、<a href="/guides/choosing-driveshaft-tubing">チューブのガイド</a>で説明しています。</li>
<li><strong>1ピースか2ピースか。</strong>2ピースは、プロペラシャフト2本に加え、センターサポートベアリング、スタブシャフト、追加のユニバーサルジョイントが必要になります。ホイールベースが長い車両には適切な選択ですが、価格帯がまったく異なります。<a href="/guides/one-piece-vs-two-piece-driveshaft">1ピースと2ピースの違い</a>をご覧ください。</li>
<li><strong>エンド部品。</strong>前側にスリップヨーク、ピニオン側にウェルドヨークという組み合わせが最もシンプルです。フランジヨークはウェルドヨークより高く、CVヘッド(ダブルカルダン)はそのどちらよりも高く、フランジ同士のプロペラシャフトにスプライン式スリップアセンブリを組み込むと、さらに加算されます。</li>
<li><strong>長さ。</strong>チューブはフィート単位で販売されるため、70インチのプロペラシャフトは50インチのものよりチューブ代が少し高くなります。また、長さによっては素材の変更や2ピースへの変更が必要になることがあり、その影響はチューブ代そのものよりはるかに大きくなります。</li>
</ol>
<p>価格に影響<em>しない</em>ものは次のとおりです。寸法そのもの(チューブの範囲内であれば、どの長さでも作業工数は同じです)、そして塗装とバランス取り(すべてのプロペラシャフトに含まれます)。</p>

