<ul class="guide-x">
<li>ご指定の寸法にカットしたDOMスチールまたは6061アルミのチューブ</li>
<li>圧入のうえ治具で溶接した、ご指定シリーズのウェルドヨーク</li>
<li>両端の新品ユニバーサルジョイント(グリース注入式またはシール式をお選びいただけます)</li>
