<p>プロペラシャフトの役割はただ一つ、タイヤとデフの減速比によって決まる速度で回転することです。そのため、振動の出方は予測できます。プロペラシャフトが原因の振動はすべて、エンジン回転数ではなく<strong>車速</strong>に従い、どのギアでも同じ速度で現れます。まずそれを確認し、そのうえで症状から部品を絞り込んでください。以下の順序は、可能性が高いものから低いもの、点検費用が安いものから高いものへと並んでいます。</p>

<h2 id="first">まず確認:プロペラシャフトが原因ですか?</h2>
<p>3つの簡単なテストで、プロペラシャフトとタイヤ、エンジン、トランスミッションを切り分けられます。</p>
<ol class="guide-steps">
<li><strong>車速かエンジン回転数か。</strong>振動が最も大きくなる速度を見つけ、同じ速度で別のギアに入れてください。振動が続く場合、原因はトランスミッションより後ろ、つまりプロペラシャフト、アクスル、またはタイヤです。エンジン回転数に応じて変わる場合は、エンジン、トルクコンバーター、またはトランスミッションが原因です。</li>
<li><strong>ニュートラルで惰性走行する。</strong>問題の出る速度でニュートラルに入れ、車を惰性で走らせます。プロペラシャフトのアンバランスや振れによる振動は変わりません。ユニバーサルジョイントの角度による振動は、トルク負荷がなくなるため軽減されることが多く、タイヤの問題はどちらの場合も同じです。</li>
<li><strong>周波数。</strong>プロペラシャフトはタイヤより3〜4倍速く回転します(デフの減速比)。タイヤのアンバランスは時速55〜65マイルで起こるゆっくりした揺れで、シートとハンドルに伝わります。プロペラシャフトのアンバランスはより速いうなりで、床、コンソール、シフトレバーに伝わり、ミラーがぼやけて見えることもよくあります。</li>
</ol>

