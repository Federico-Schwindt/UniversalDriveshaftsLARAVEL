<h2 id="ujoints">ユニバーサルジョイントの摩耗</h2>
<p>ユニバーサルジョイントは、各キャップ内のニードルベアリングが摩耗します。最初のサインは、グリースが切れて出る乾いたキーキー音です。次にガタが出て、トルクが反転するとき(ギアを入れたとき、アクセルオフからオンに切り替えたとき)にゴツンという感触になります。ガタがあるとプロペラシャフトが中心からずれ、中心のずれたプロペラシャフトはバランスが崩れるため、摩耗したユニバーサルジョイントは結局振動にもつながります。</p>
<p>点検方法:トランスミッションをニュートラルにし、パーキングブレーキを解除して、車輪に輪止めをします。各ユニバーサルジョイントのそばでプロペラシャフトを持ち、ヨークに対して回そうとし、さらに上下にも押してみてください。目で見える、または手で感じられる動きはすべて許容範囲を超えています。各キャップに赤茶色の錆の粉の輪がないか確認してください。これはニードルベアリングがすり減って粉になったものです。緩んだキャップが当たり続けたせいで、ヨークの耳の穴が楕円形になっていないかも確認してください。交換用のユニバーサルジョイントは<a href="/shop/driveshaft-components/u-joints">ユニバーサルジョイント</a>にシリーズ別に掲載しています。シリーズは<a href="/guides/u-joint-series-identification-chart">一覧表</a>で確認してください。ヨークの耳が摩耗している場合は、ユニバーサルジョイントだけでなくヨークも交換が必要です。</p>

<h2 id="balance">バランスとウェイトの脱落</h2>
<p>プロペラシャフトは、バランス測定機にかけながら、両端付近のチューブに小さなウェイトを溶接してバランスを取ります。ウェイトのない、きれいな長方形の跡や溶接跡を探してください。それはウェイトが脱落したしるしです。チューブの片側に泥や防錆剤が溜まってもアンバランスになり、小石やジャッキでチューブがへこんだ場合も同様です。へこみは肉厚の分布を変えてしまうため、バランス調整では確実に補正できません。</p>
<p>振れ(ランアウト)も、バランスを損なうもう一つの原因です。車載状態でプロペラシャフトを手で回し(後輪を浮かせ、ニュートラルで)、ダイヤルゲージまたは固定したポインターをチューブに当てて測ります。端付近で全振れが約0.010インチ、中央で0.015インチを超える場合は、チューブまたはヨークが曲がっており、ウェイトでは滑らかにできません。軽度の振れは、バランス調整の前に整形で直せます。大きな振れの場合は、新しいチューブが必要です。</p>

<h2 id="phasing">位相</h2>
<p>プロペラシャフトの2つのユニバーサルジョイントは、ヨークが互いに<strong>揃う</strong>ように(同位相で)取り付ける必要があります。ユニバーサルジョイントは角度がついた状態で作動すると、1回転につき2回加速と減速を繰り返します。ヨークが揃っていれば、2つ目のジョイントが1つ目の影響を打ち消します。片方のジョイントを90度ずらすと、影響は打ち消されずに加算され、プロペラシャフトは回転速度の2倍の周波数で振動します。1ピースのプロペラシャフトが位相ずれを起こすのは、切断して再溶接した場合だけです。2ピースの場合は、両半分の間のスプライン式スリップ部分を、合いマークを合わせずに組み直すたびに位相がずれます。片端からプロペラシャフトを見通して、前側と後ろ側のヨークの耳が揃っているか確認してください。90度ずれている場合は、直すのに費用はかかりません。</p>

<h2 id="angles">作動角</h2>
<p>ユニバーサルジョイントの作動角とは、プロペラシャフトの中心線と、それが駆動するヨークとの差です。角度が大きすぎる場合や、両端の角度が等しく逆向きになっていない場合は、負荷時に振動が現れ、速度とともに悪化します。リフトアップしたトラック、ローダウンした車、アクスルやトランスミッションを交換した車は、よくある原因です。測り方と修正方法は<a href="/guides/driveshaft-angles-and-pinion-angle">角度ガイド</a>で説明しています。要点は、各ジョイントを1〜3度の範囲で作動させ、2つの角度の差を0.5度以内に収め、負荷がかかったときに一直線になるようピニオンを調整することです。</p>

<h2 id="csb">センターサポートベアリング</h2>
<p>2ピースのプロペラシャフトでは、センターサポートベアリングがゴム製のマウントで駆動系の中間を支えています。ベアリングが壊れると、速度とともにうなり音やゴロゴロ音が出ます。ゴムが壊れると、プロペラシャフトが垂れ下がったり跳ねたりして、隣り合う2つのユニバーサルジョイントの角度が変わり、振動や発進時の震えが起こります。点検は負荷のない状態で行います。ベアリングの両側を持ってガタを確認し、ゴムの亀裂や破れ、プロペラシャフトがサポートの中で明らかに偏っていないかを確認してください。交換は簡単な作業で、<a href="/guides/center-support-bearing-replacement">センターサポートベアリングのガイド</a>で手順を説明しています。シャフト径別に、<a href="/shop/driveshaft-components/center-support-bearing">ほとんどのトラックに対応するセンターサポートベアリング</a>を取り揃えています。</p>

<h2 id="inspect">10分間の点検</h2>
<ul class="guide-x">
<li>いずれかのユニバーサルジョイントのキャップに錆の粉や湿り気がないか</li>
<li>プロペラシャフトを動かしたとき、ユニバーサルジョイントにガタを感じないか</li>
<li>ヨークの耳が楕円形になっていたり、打痕がついていないか</li>
<li>溶接されていたウェイトの跡にきれいな部分がないか</li>
<li>チューブにへこみ、深い傷、目に見える曲がりがないか</li>
<li>両端のヨークの耳が揃っているか(位相)</li>
<li>スリップヨークのスプライン:乾いていないか、錆びていないか、回転方向のガタが見えないか</li>
<li>センターサポートのゴムが破損しておらず、プロペラシャフトがサポートの中心にあるか</li>
<li>ピニオンナットが締まっており、ピニオンフランジにガタがないか</li>
<li>車高が通常の状態で角度を測定し、記録したか</li>
</ul>
