<h2 id="convert">2ピースから1ピースへの変換</h2>
<p>変換する理由は3つあります。センターサポートが何度も故障した、車高を上げたため2ピースのプロペラシャフトの角度の管理が難しくなった、部品点数を減らしたい、というものです。全長(トランスミッション出力から、走行時の高さでのピニオンまで)が上の表の1ピースチューブで対応できる範囲であれば、変換は可能です。実際には、62〜70インチの範囲にあるレギュラーキャブのロングベッド車や、エクステンデッドキャブのショートベッド車で、3.500のスチールまたは4.000のアルミで製作する場合が該当します。70インチを超えると、1ピースでは、トンネルに収まらないほど大きなチューブが必要になるか、高速道路を走るために必要な回転数よりも制限回転数が低くなってしまいます。</p>
<p>変換に必要なものは、正しく測定した全長(<a href="/guides/how-to-measure-a-driveshaft">測定ガイド</a>をご覧ください)、新しいスリップヨーク用のトランスミッション出力スプライン、ピニオンヨークのシリーズまたはフランジパターン、そして作動角度の確認です。1ピースのプロペラシャフトはトランスミッションからピニオンまで1本の直線上を通るため、ピニオン角度の変更が必要になる場合があります。クロスメンバーとブラケットは使わなくなります。数値がそろえば、<a href="/online-builder">1ピース用の「Arma tu cardán」</a>で注文を進められます。</p>
<p>逆に、1ピースから2ピースへの変換はまれで、ベアリング用の純正クロスメンバーがある車両、つまり、もともと2ピースのプロペラシャフトが付いていたロングホイールベースのシャシーでのみ意味があります。</p>

