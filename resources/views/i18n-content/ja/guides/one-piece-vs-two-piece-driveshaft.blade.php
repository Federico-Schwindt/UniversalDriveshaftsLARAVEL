<p>全長と回転数によって、車両に1ピースのプロペラシャフトを使うか、2ピースのプロペラシャフトを使うかが決まります。直径に対して長すぎるチューブは、高速道路を走行する程度の速度でたわみ、振れ回りを起こします。解決策は、より太いチューブにするか、より軽い素材にするか、プロペラシャフトを2分割して中間部を支えることです。判断すべき点はこれだけです。このガイドでは、実際の数値を使って判断の流れを説明し、2ピースのプロペラシャフトで何が追加されるのか(そして何が故障しうるのか)、さらに一方から他方への変換についても解説します。どちらも <a href="/online-builder">Arma tu cardán</a> でオーダーメイド製作でき、2ピースは当店でお見積りしますので、<a href="/contact">寸法をお送りください</a>。</p>

<h2 id="difference">違い</h2>
<p><strong>1ピース</strong>のプロペラシャフトは、両端にヨークが付いた1本のチューブと、2つのユニバーサルジョイントで構成されます。スライド機構は、通常、トランスミッション出力側のスリップヨークです。<strong>2ピース</strong>のプロペラシャフトは、直列に並んだ2本のチューブで構成されます。前側の部分はスタブ(中間シャフト)で終わり、このスタブにはシャシーのクロスメンバーにボルト止めされたブラケットに取り付けられたセンターサポートが付きます。後ろ側の部分はスリップヨークまたはスプラインスリーブから始まり、これがスタブ上で作動して、ピニオンで終わります。そのため、2ピースのプロペラシャフトにはユニバーサルジョイントが3つ、センターサポートベアリング、中間部の精密なスライドスプライン、そして多くの場合、固定式(スライドしない)の前側ヨークまたはフランジが付きます。スライドはスタブ側で行われるためです。</p>

