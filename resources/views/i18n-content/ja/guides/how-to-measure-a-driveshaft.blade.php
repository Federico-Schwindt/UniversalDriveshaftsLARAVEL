<p>写真があると助かります。プロペラシャフト全体を横から写した写真、各端部を正面から写した写真、チューブやヨークに刻印されたラベルや番号の写真をご用意ください。Spicer、Neapco、純正のプロペラシャフトには、シリーズがすぐにわかる部品番号が付いていることがよくあります。</p>

<h2 id="mistakes">再製作になりかねない間違い</h2>
<ul class="guide-x">
<li><strong>ヨークの耳の先端まで測定する。</strong>耳はシリーズやメーカーによって異なります。クロスの中心は変わりません。</li>
<li><strong>スリップヨークを中途半端に伸ばした状態で測定し、その旨を伝えない。</strong>その場合、長さはその日のスプラインの位置によって変わってしまいます。</li>
<li><strong>シャシーリフトにのせ、アクスルが垂れ下がった状態で測定する。</strong>プロペラシャフトが完全に伸びた状態になります。走行時の車高では、サスペンションのストロークの分だけ短くなります。</li>
<li><strong>直径ではなく円周を測る。</strong>2.500のチューブは、円周が7.85です。7.85を直径として伝えれば明らかな間違いですが、誤って換算した3.000を伝えた場合は、間違いに気付きにくくなります。</li>
<li><strong>2ピースのプロペラシャフトで位相のマークを忘れる。</strong>プロペラシャフトが180度ずれた状態で再び組み立てられ、振動は新しい部品のせいだとされてしまいます。</li>
<li><strong>ユニバーサルジョイントのシリーズを記載しない。</strong>1310と1330はカップの直径が同じで、1メートル離れて見ると見分けがつきません。</li>
</ul>

