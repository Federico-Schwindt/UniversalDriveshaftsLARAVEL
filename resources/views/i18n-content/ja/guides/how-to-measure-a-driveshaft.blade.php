<p>長さだけではプロペラシャフトは決まりません。両端はそれぞれ車両に適合する必要がありますので、寸法と合わせて次のデータを集めてください。</p>
<div class="dtable-wrap"><table class="dtable">
<thead><tr><th>端部のタイプ</th><th>記録する内容</th><th>方法</th></tr></thead>
<tbody>
<tr><td>スリップヨーク</td><td>スプラインの歯数、外径、ユニバーサルジョイントのシリーズ</td><td>歯数を数え、ノギスで端から端まで測定します。ユニバーサルジョイントのカップを測定します(<a href="/guides/u-joint-series-identification-chart">シリーズ一覧表</a>)</td></tr>
<tr><td>エンドヨーク(ピニオンまたはトランスファーケース側)</td><td>ユニバーサルジョイントのシリーズ、ストラップ式またはUボルト式のタイプ</td><td>カップの直径と幅。カップがストラップ、Uボルト、ボルト止めのカップのどれで固定されているかを記録します</td></tr>
