<p>プロペラシャフトは特定の長さで製作されます。その長さが間違っていれば、他のことは何も意味がありません。全米の工場は同じ方法、同じ基準点で測定します。プロペラシャフトを構成する部品(ヨーク、チューブ、ユニバーサルジョイント)は、<strong>ユニバーサルジョイントのクロスの中心線</strong>と<strong>フランジの面</strong>を基準に定義されるためです。この2つの基準を覚えれば、以下のすべての寸法が自然に収まります。このガイドでは、当店の<a href="/driveshaft-designer">プロペラシャフトデザイナー</a>と同じ記号を使用していますので、プロペラシャフトを描き、数値を入力して、シートを印刷または送信することができます。</p>

<h2 id="refs">基準:A、B、C、W、T</h2>
<p>5つの記号で、あらゆるプロペラシャフトを表すことができます。1ピースのプロペラシャフトではC、W、Tを使用します。2ピースのプロペラシャフトではAとBが加わり、前側のプロペラシャフトを1、後側を2として番号を付けます。</p>
<div class="dtable-wrap"><table class="dtable">
<thead><tr><th>記号</th><th>内容</th><th>測定の起点</th><th>測定の終点</th></tr></thead>
<tbody>
<tr><td>A</td><td>アセンブリ全体の全長</td><td>前端の基準(ユニバーサルジョイントの中心またはフランジ面)</td><td>後端の基準</td></tr>
<tr><td>B1 / B2</td><td>前端からセンターサポートまで、センターサポートから後端まで</td><td>端部の基準</td><td>ベアリングの中心(ゴムダンパーの中間)</td></tr>
<tr><td>C1 / C2</td><td>各プロペラシャフト単体の長さ</td><td>ユニバーサルジョイントの中心またはフランジ面</td><td>そのプロペラシャフトのもう一方の端のユニバーサルジョイントの中心またはフランジ面</td></tr>
<tr><td>W1 / W2</td><td>チューブの長さ(溶接部から溶接部まで)</td><td>前側の溶接ビード</td><td>後側の溶接ビード</td></tr>
<tr><td>T</td><td>チューブの外径</td><td colspan="2">溶接部とバランスウェイトから離れた位置で、チューブにノギスを当てて測定</td></tr>
</tbody></table></div>
<p>端部の基準は2つのルールで決まります。端部に<strong>ユニバーサルジョイント</strong>(スリップヨーク、エンドヨーク、クロス付きのウェルドヨーク)がある場合、基準は<strong>クロスの中心</strong>で、ベアリングカップの中心線として確認できます。端部が<strong>フランジ</strong>(フランジヨーク、CVフランジ、コンパニオンフランジ)の場合、基準は相手側の部品にボルトで固定される<strong>フランジの面</strong>です。ヨークの耳の先端やカップの縁までは絶対に測らないでください。</p>

<div class="guide-note"><b>なぜクロスの中心なのですか?</b> カタログのすべてのヨークは「中心線から端まで」の寸法で表記されています(5.000 CLと表記されたスリップヨークは、スプライン端からクロスまでが5インチです)。ユニバーサルジョイントの中心間の長さをお知らせいただければ、ヨークの寸法を差し引いて、チューブを正確にカットします。</div>

<h2 id="tools">必要なもの</h2>
<ul>
<li>スチールテープ、または24インチ未満の測定にはより適した硬い定規。布製のテープは伸びてしまいます。</li>
<li>チューブの外径とスプラインの直径を測るノギス。チューブに巻いたテープでわかるのは円周であり、直径ではありません。</li>
<li>分解する前にヨークの位相を記録するための、ペイントマーカーまたはチョーク。</li>
<li>車両上で測定する場合は、サスペンションに荷重がかかった<strong>走行時の車高</strong>の状態にしてください。ジャッキスタンドはシャシーの下ではなく、車軸の下に置きます。</li>
</ul>

<h2 id="one-piece">1ピースのプロペラシャフトの測り方</h2>
<p>ほとんどの1ピースのプロペラシャフトは、3つのケースのいずれかに当てはまります。まず両端を確認してから測定してください。</p>
<h3>トランスミッション側がスリップヨーク、アクスル側がエンドヨークまたはフランジ</h3>
<ol class="guide-steps">
<li>スリップヨークをトランスミッションの出力軸に突き当たるまで押し込みます。当店の<a href="/online-builder">プロペラシャフトビルダー</a>は、この完全に圧縮した状態の長さを想定しています。</li>
<li><strong>C</strong>は、前側のユニバーサルジョイントのクロス中心から、後側のクロス中心(ピニオン側がエンドヨークの場合)、または後側のフランジ面(ピニオン側がフランジヨークの場合)まで測定します。</li>
<li><strong>W</strong>は、チューブに沿って溶接ビードからビードまで測定します。</li>
<li><strong>T</strong>(チューブの外径)は、ノギスで測定します。一般的なサイズは、スチールで2.000、2.500、3.000、3.500インチ、アルミで3.500~4.000インチです。</li>
<li>スリップヨークのスプラインを記録します。スプラインの歯数を数え、ノギスで外径を測定してください。1.250 x 16、1.375 x 16、1.500 x 16で、ほとんどのライトトラックに対応できます。</li>
</ol>
<h3>フランジからフランジ(スリップヨークなし)</h3>
<p>多くの輸入車、最近のトラック、そしてすべての産業用プロペラシャフトは、両端にボルト止めのフランジが付いています。スライド機能はプロペラシャフトの内部(スプライン式スリップアセンブリ)にあるか、存在しません。取り付けた状態で、走行時の車高にて、<strong>C</strong>をフランジ面からフランジ面まで測定します。圧縮位置も伸長位置も気にする必要はありませんが、余裕もありません。数値は1/16インチ単位で正確でなければなりません。各フランジについて、<strong>ボルトサークルの直径</strong>、<strong>穴の数とサイズ</strong>、<strong>センターリングの直径</strong>(フランジの中心を合わせる突き出た、または凹んだリング)を記録してください。<a href="/guides/slip-yoke-vs-weld-yoke-vs-flange-yoke">ヨークガイド</a>では、フランジの見方を説明しています。</p>
<h3>プロペラシャフトなしで車両上から測る方法</h3>
<p>古いプロペラシャフトがない場合や、誤ったものである場合は、車両を測定します。サスペンションに荷重がかかった状態で、トランスミッションの出力側からピニオンまでを測定します。出力側ヨークのクロス中心からピニオンヨークのクロス中心まで、スリップヨークがない場合はシール面からフランジ面までです。どの基準を使用したかをお知らせください。また、出力軸のスプライン(歯数と直径)と、ピニオンヨークのシリーズまたはフランジのパターンも必要です。</p>

<h2 id="two-piece">2ピースのプロペラシャフトの測り方</h2>
<p>2ピースのプロペラシャフトは、スタブシャフト(中間軸)上の<strong>センターサポート</strong>で終わる前側のプロペラシャフトと、そのスタブシャフトにスライドして取り付けられる後側のプロペラシャフトで構成されます。ベアリングサポートはクロスメンバーにボルトで固定されるため、その位置は車両によって決まります。そのため、全長のAだけでなく、2つのB寸法が必要になります。</p>
<ol class="guide-steps">
<li>位相をマークします。2つのプロペラシャフトの間のスプラインスリップジョイントをまたぐようにペイントで線を引き、後側のヨークが同じ回転位置に戻るようにします。</li>
<li><strong>A</strong>は、スリップジョイントが取り付け位置にある状態で、前側の基準から後側の基準まで測定します。</li>
<li><strong>B1</strong>は、前側の基準からセンターサポートの中心(サポート面ではなく、ゴムの中間点)まで測定します。<strong>B2</strong>は、ベアリングの中心から後側の基準まで測定します。B1 + B2はAと一致するはずです。一致しない場合は、測り直してください。</li>
<li><strong>C1</strong>(前側のプロペラシャフト)は、前側の基準から後側のユニバーサルジョイント(ベアリングの後ろ)のクロス中心まで、<strong>C2</strong>(後側のプロペラシャフト)は、そのクロス中心から後側の基準まで測定します。</li>
<li><strong>W1</strong>と<strong>W2</strong>は、各チューブの溶接部から溶接部まで測定し、それぞれの<strong>T</strong>をノギスで測定します。前側と後側のチューブは、直径が異なることがよくあります。</li>
<li>スタブシャフトのスプライン(歯数と直径)と、ベアリングサポートのタイプを記録します。<a href="/guides/center-support-bearing-replacement">センターサポートベアリングのガイド</a>では、その見分け方を説明しています。</li>
</ol>
<p>車両しかない場合は、ベアリングのクロスメンバーを見つけ、B1はトランスミッションの出力側からクロスメンバーのボルトパターンの中心まで、B2はそこからピニオンまで測定します。<a href="/driveshaft-designer/2">デザイナーの2ピース図</a>では、これらの各寸法にラベルが付いているので、測り忘れを防げます。</p>

