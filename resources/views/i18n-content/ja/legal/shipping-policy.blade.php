  <h2>1. 処理期間</h2>
  <p>平日の東部標準時（EST）午後2時までにご注文いただいた場合は、ほとんどの在庫品を当日中に発送しますが、ご注文の量によって処理期間が前後する場合があります。発送確認メールをお送りしますので、受信トレイをご確認ください。それ以降のご注文、週末または祝日のご注文は、通常、翌営業日に発送します。特注および新品のプロペラシャフトは、処理に最大5営業日かかります。指定の長さにカットするチューブおよび取り寄せ品は、製作または入荷後に発送します。納期の目安は商品ページに表示されるか、ご注文後に個別にご連絡します。運送会社が案内する配達日数は目安であり、保証されるものではありません。</p>

