  <h2>3. 貨物便(LTL)での発送</h2>
  <p><b>チューブまたは完成品のプロペラシャフトが5本以上</b>のご注文、<b>100 lb以上</b>のご注文、および<b>108インチを超える</b>単品の部品を含むご注文は、パレットに固定してLTLトラック貨物便で発送します。同じご注文のその他の商品も同じパレットで届きます。貨物便の料金は、チェックアウト時にリアルタイムで表示されます。</p>
  <ul>
    <li><b>お届け先。</b>貨物便の料金は、荷受け用のドックがある事業所への配送を前提としています。ご自宅への配送や、ドックがなくリフトゲートが必要な場所への配送の場合は、料金に含めるため、チェックアウト時にお知らせください。</li>
    <li><b>荷物の受け取り。</b>運送会社から日程調整のお電話があります。お届けの際は、受け取れる方がお待ちください。署名の前にパレットを確認し、目に見える破損があれば、配達受領書に記入してください。</li>
    <li><b>貨物便には送料無料は適用されません。</b>また、送料無料クーポンも貨物便の料金には使えません。</li>
  </ul>

