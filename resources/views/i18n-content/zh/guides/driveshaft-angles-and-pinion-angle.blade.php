<p>单个万向节并不是等速万向节。当它在一定角度下工作时，即使输入端转动均匀，输出轴每转一圈也会加速和减速两次。角度越大，速度波动越大。传动轴之所以能容忍这一点，是因为它有<strong>两个</strong>万向节：如果两个万向节以<strong>相等的角度</strong>工作，并且万向节叉<strong>相位一致</strong>，第二个万向节就会抵消第一个万向节造成的波动，主动齿轮便能平稳转动。调整传动轴角度，就是要在行驶高度下实现这一点，并在加速时保持住。你需要一个数字倾角仪、一块水平的地面，以及二十分钟时间。</p>

<h2 id="why">角度为什么重要</h2>
<p>角度不对时，会出现三个问题。<strong>振动</strong>：角度不相等会留下残余的速度波动，频率为传动轴转速的两倍，表现为带负载时出现、并随车速升高而加剧的振动。<strong>万向节寿命</strong>：角度过大的万向节会冲击其滚针轴承，导致过早失效；角度为零的万向节，其滚针永远不会转动，会在十字轴上压出压痕，同样会过早失效。最理想的范围是 <strong>1 到 3 度</strong>的工作角度。<strong>滑动叉行程</strong>：在较短的传动轴上，角度过大会使滑动叉随悬架行程伸缩更多，可能使其顶到底，或从花键中脱出。<a href="/guides/driveshaft-vibration-and-noise-diagnosis">振动指南</a>说明了角度在诊断流程中所处的位置；本指南则是具体的操作步骤。</p>

<h2 id="measure">如何测量三个角度</h2>
<p>你需要三个读数，全部在同一平面内（垂直平面，从侧面看），车辆处于行驶高度并停在水平地面上。</p>
<ol class="guide-steps">
<li><strong>变速箱（或分动箱）输出角度。</strong>将倾角仪放在与输出轴平行的平整机加工表面上：滑动叉筒体的底部、转到垂直位置的输出法兰端面，或已知与输出轴平行的变速箱油底壳边缘。记录读数及其方向（向上倾或向下倾）。</li>
<li><strong>传动轴角度。</strong>将倾角仪放在传动轴管上，避开平衡块和焊缝。记录读数及其方向。</li>
<li><strong>主动齿轮角度。</strong>将倾角仪放在主动齿轮万向节叉的平面部位（转到垂直位置），或放在转到垂直位置的主动齿轮法兰端面，或放在已知与主动齿轮平行的差速器壳盖法兰底部。记录读数及其方向。</li>
</ol>
<p>每个<strong>万向节工作角度</strong>，等于传动轴角度与其所连部件角度之差。如果变速箱读数为向下 3 度，传动轴为向下 1 度，则前万向节的工作角度为 2 度。如果主动齿轮读数为向上 1 度，传动轴为向下 1 度，则后万向节的工作角度为 2 度。别忘了俯视平面：在传动轴偏置或变速箱不居中的车辆上，还要从下方测量水平面内的角度并加以合成。大多数卡车的横向偏置小到可以忽略，但有时会特意加入几度水平偏置，以保持滚针转动。</p>

<h2 id="rule">相等且相反的原则</h2>
<p>在常规的双万向节传动轴上，变速箱输出轴中心线与主动齿轮中心线应当<strong>平行</strong>，传动轴则在两者之间呈一定角度。这样，两个万向节的角度相等、方向相反（传动轴前端向下折、后端向上折，或相反），速度波动便会相互抵消。目标值如下：</p>
<div class="dtable-wrap"><table class="dtable">
<thead><tr><th>项目</th><th>目标值</th><th>公差</th></tr></thead>
<tbody>
<tr><td>每个万向节的工作角度</td><td>1 到 3 度</td><td>绝不能为 0；超过 3 度仅限在下方转速限值之内</td></tr>
<tr><td>两个万向节角度之差</td><td>0</td><td>最大 0.5 度，绝对上限 1 度</td></tr>
<tr><td>变速箱与主动齿轮的中心线</td><td>平行</td><td>同样的 0.5 度</td></tr>
<tr><td>万向节叉相位</td><td>对齐</td><td>沿传动轴方向看，叉耳对齐</td></tr>
</tbody></table></div>
<p>一个常见的误解是传动轴应该是直的。完全笔直的传动系，两个万向节的角度均为零，而零角度本身就是一种失效方式：滚针轴承永远不会滚动，会在十字轴轴颈上磨出一道沟槽。原厂设置会特意留出一两度的角度。</p>

