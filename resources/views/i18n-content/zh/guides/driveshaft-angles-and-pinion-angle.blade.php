<p>这些是限值，而不是目标值。以 2,200 RPM 行驶的皮卡，只要两个万向节角度相等，可以在 6 度下工作，但在 3 度时会运转得更平稳，万向节也更耐用。在越野低速行驶时，万向节可能短时间在 15 到 20 度下工作，这正是加高车辆的常态，所以它们在大角度一端使用双万向节（见下文）。</p>

<h2 id="pinion">如何调整主动齿轮角度</h2>
<p>主动齿轮是唯一容易调整的部件，所以修正角度通常就是修正主动齿轮。难点在于<strong>车桥扭转</strong>：加速时，车桥壳体会绕其中心线向上抬头，顶住悬架，使主动齿轮角度增大。因此主动齿轮要调到<em>带载时</em>正确，也就是静止时略微偏低。</p>
<ul>
<li><strong>钢板弹簧：</strong>静止时将主动齿轮调到比平行位置向下 1 到 3 度（弹簧越软、卡车越重、动力越大，数值越大）。可以在弹簧与其座之间加钢制楔块（2 度、4 度和 6 度为标准规格），或切割后重新焊接弹簧座。超过约 6 度的楔块应更换为新的弹簧座。</li>
<li><strong>连杆和螺旋弹簧悬架：</strong>扭转很小，所以静止时向下 0.5 到 1 度。可通过上控制臂的长度或可调控制臂来调整。</li>
<li><strong>装有滑动叉分动箱的加高皮卡：</strong>加高会使后传动轴大幅向下倾斜。将主动齿轮向上转以与之匹配（分动箱与主动齿轮平行），并确认分动箱处的前万向节没有超过其转速限值。如果超过，请改用 CV 传动轴。</li>
<li><strong>降低车身的汽车：</strong>传动轴变得更平，万向节角度趋近于零。请用楔块或调整控制臂，特意加入一两度角度，让滚针保持转动。</li>
</ul>
<p>任何调整之后，都要重新测量三个角度，并在悬架完全伸展和完全压缩两种状态下检查滑动叉的配合。然后进行路试，在之前出现振动的车速下加速。</p>

<h2 id="cv">什么时候答案是 CV 或双万向节传动轴</h2>
<p><strong>双万向节</strong>（CV）总成把两个万向节背靠背装在传动轴一端的定心叉上。这一对万向节会抵消自身的速度波动，所以传动轴在这一端可以大角度工作（连续 12 到 15 度，短时更大）而不会带来振动。这样，<em>另一</em>端的单万向节就必须在<strong>接近零</strong>的角度下工作：CV 传动轴的规则是让主动齿轮直接对准传动轴，相对传动轴中心线向下约 0.5 到 1 度以补偿扭转，而不是与变速箱保持平行。当加高或几何条件使相等且相反的原则无法实现时，当 4x4 的前万向节超过其转速限值时，或者短轴距车辆的前传动轴在分动箱处角度很陡时，请使用 CV 传动轴。我们可以制造所有常见系列的 CV 传动轴；<a href="/shop/driveshaft-components/cv-double-joints-heads">双万向节总成</a>和 <a href="/shop/driveshaft-components/cv-flange-yokes">CV 法兰叉</a>都在目录中，<a href="/online-builder">在线定制传动轴</a>也提供 CV 总成作为端部选项。如果几何条件让你无从下手，<a href="/contact">把你的三个角度和加高高度发给我们</a>，我们会告诉你该用哪种传动轴以及主动齿轮角度调到多少。</p>