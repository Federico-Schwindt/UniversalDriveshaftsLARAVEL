<p>传动轴只做一件事：以车轮和差速器速比决定的转速旋转。这使它的振动具有可预测性。传动轴引起的任何问题都会跟随<strong>车速</strong>，而不是发动机转速，并且在同一车速下的所有挡位中都会出现。先确认这一点，再根据症状判断是哪个部件。下面的顺序是按可能性从高到低、按检查成本从低到高排列的。</p>

<h2 id="first">首先：是传动轴的问题吗？</h2>
<p>三个快速测试可以把传动轴与轮胎、发动机和变速箱区分开。</p>
<ol class="guide-steps">
<li><strong>车速还是转速？</strong>找到振动最严重的车速，然后在同一车速下换到另一个挡位。如果振动依旧，说明问题在变速箱之后：传动轴、车桥或轮胎。如果振动随发动机转速变化，则是发动机、液力变矩器或变速箱的问题。</li>
<li><strong>空挡滑行。</strong>在出现问题的车速下挂入空挡，让车辆继续滑行。传动轴因不平衡或跳动超差引起的振动不会变化；万向节角度引起的振动通常会减轻，因为扭矩负载消失了；轮胎问题则在两种情况下完全相同。</li>
<li><strong>频率。</strong>传动轴的转速比车轮快3到4倍（即差速器速比）。轮胎不平衡表现为55到65 mph之间较慢的抖动，在座椅和方向盘上能感觉到。传动轴不平衡则是更快的嗡嗡声，在地板、中控台和变速杆上能感觉到，并且常常使后视镜里的影像变得模糊。</li>
</ol>

