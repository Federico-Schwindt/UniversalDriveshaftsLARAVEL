<h2 id="ujoints">万向节磨损</h2>
<p>万向节的磨损发生在每个轴承盖内的滚针轴承上。最初的征兆是因缺油而发出的干涩吱吱声；接下来是旷量，在扭矩反向时（挂挡时、从松油门转为加速时）感觉像是一下撞击。旷量会使传动轴偏离中心，而偏心的传动轴就不再平衡，所以磨损的万向节最终也会变成振动。</p>
<p>检查方法：变速箱挂空挡，松开手刹，用楔块挡住车轮。在每个万向节旁握住传动轴，试着相对于万向节叉转动它，然后再上下推动。任何能看到或感觉到的移动都说明已经过大。在每个轴承盖上寻找一圈红褐色的铁锈粉末：那是滚针轴承被磨成了粉末。检查万向节叉耳部的孔是否因轴承盖松动反复撞击而变成椭圆形。更换用的万向节按系列列在<a href="/shop/driveshaft-components/u-joints">万向节</a>页面；请用<a href="/guides/u-joint-series-identification-chart">对照表</a>确定系列。如果叉耳已经磨损，就需要更换万向节叉，而不是只换万向节。</p>

<h2 id="balance">平衡与平衡块脱落</h2>
<p>传动轴是在机器上通过在靠近两端的管上焊接小平衡块来进行平衡的。寻找一块干净的长方形痕迹或没有平衡块的焊点：说明平衡块掉了。积聚在管一侧的泥土和防锈涂层同样会造成不平衡，被石头或千斤顶砸出凹坑的管也一样。凹坑会改变管壁厚度的分布，无法通过平衡可靠地补偿。</p>
<p>跳动量是平衡的另一个大敌。在车上转动传动轴（后轮悬空，空挡，用手转动），用百分表或固定的指针靠在管上。靠近两端处总跳动量超过约0.010英寸，或中部超过0.015英寸，就说明管或某个万向节叉已经弯曲，任何平衡块都无法让它运转平稳。轻微的跳动，修理厂会先校直再平衡；跳动量大则意味着要换新管。</p>

<h2 id="phasing">相位</h2>
<p>传动轴上的两个万向节必须安装成其万向节叉彼此<strong>对齐</strong>（同相）。万向节在有角度工作时，每转一圈会加速和减速两次；万向节叉对齐时，第二个万向节会抵消第一个所造成的影响。把一个万向节转90度，两者的影响就会叠加而不是抵消，传动轴会以两倍于其转速的频率振动。单段传动轴只有在被切断后重新焊接时才可能相位错误。两段式传动轴则在两半之间的花键滑动接头重新装配而没有对准标记时就会相位错误。从一端沿传动轴方向看：前后万向节叉的耳部应当对齐。如果相差90度，修复是免费的。</p>

<h2 id="angles">工作角度</h2>
<p>万向节的工作角度，是传动轴中心线与其所驱动的万向节叉之间的差值。角度过大，或两端的角度不相等且方向不相反，就会产生带载荷时出现、并随车速升高而加剧的振动。抬高的皮卡、降低的轿车，以及更换过车桥或变速箱的车辆是常见的嫌疑对象。<a href="/guides/driveshaft-angles-and-pinion-angle">角度指南</a>讲解了如何测量和修正；简言之，每个万向节的工作角度应在1到3度之间，两者相差应在半度以内，并且小齿轮应当调整到在负载下转动后恰好对齐。</p>

<h2 id="csb">中间支撑轴承</h2>
<p>在两段式传动轴中，中间支撑轴承通过橡胶减震块托住传动轴的中部。轴承失效时，会随车速出现嗡嗡声或轰鸣声。橡胶失效时，传动轴会下垂或跳动，这会改变相邻两个万向节的角度，造成振动或起步时的抖动。检查时让传动轴不受载荷：握住轴承两侧，感觉是否有旷量；查看橡胶是否有裂纹或撕裂，或者传动轴在支架中是否明显偏心。更换是一项简单的工作，在<a href="/guides/center-support-bearing-replacement">中间支撑轴承指南</a>中有说明，我们按轴径提供<a href="/shop/driveshaft-components/center-support-bearing">适用于大多数卡车的中间支撑轴承</a>。</p>

<h2 id="inspect">十分钟检查</h2>
<ul class="guide-x">
<li>任何万向节轴承盖上有铁锈粉末或潮湿</li>
<li>晃动传动轴时在万向节上感觉到任何旷量</li>
<li>万向节叉耳部呈椭圆形或被撞击过</li>
<li>原来焊有平衡块的位置出现干净的痕迹</li>
<li>传动轴管上有凹坑、深划痕或肉眼可见的弯曲</li>
<li>两端万向节叉的耳部对齐（相位）</li>
<li>滑动叉花键：干涩、生锈，或能看到转动旷量</li>
<li>中间支撑橡胶完好，传动轴在支架中居中</li>
<li>小齿轮螺母拧紧，小齿轮法兰没有旷量</li>
<li>在行驶高度下测量角度并记录</li>
</ul>
