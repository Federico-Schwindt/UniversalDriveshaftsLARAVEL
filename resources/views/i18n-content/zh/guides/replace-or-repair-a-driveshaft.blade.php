<h2 id="upgrade">何时应该升级而非更换</h2>
<p>重复发生的故障就是信息。一个只能用一年的万向节说明它工作时角度过大，或是等级扭矩过大而没有涂油。一根丢失平衡重块的传辅轿管从本就从未直过。如果车辆自传动轿制造以来发生了变化（功率、敲高、轮胎、拖拉），利用更换的机会升级系列，改用更大的或铲合金传辅轿管，在高角度端添加 CV 头或在小齿轮允许的地方改为法兰。<a href="/guides/driveshaft-angles-and-pinion-angle">角度指南</a>和<a href="/guides/choosing-driveshaft-tubing">传辅轿管指南</a>涵盖了每一个决策；<a href="/online-builder">定制您的传动轿</a>可以报出结果。</p>

