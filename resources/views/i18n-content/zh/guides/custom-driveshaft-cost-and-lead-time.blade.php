<p>定制传动轴的报价取决于几项关键选择，只要弄清每一项会增加多少费用，就不会有意外。本指南说明了哪些因素决定价格、报价包含哪些内容、我们目录中各部件的实际价格（让您看清钱花在哪里），以及您可以预期的交货时间。<a href="/online-builder">自助配置传动轴</a>可以实时为您计算：选择使用类型、系列、材料和万向节叉，输入尺寸，屏幕上就会显示成品并已平衡的传动轴价格。</p>

<h2 id="drivers">影响价格的五大因素</h2>
<ol class="guide-steps">
<li><strong>系列。</strong>十字轴的系列决定了每个万向节叉和十字轴的尺寸。1310 和 1330 系列的零件最便宜、货源最充足；1350 略贵一些；1410、1480 和 1550 更贵，因为锻造件更大，可选的万向节叉也更少。请选择车辆原有的系列，除非您是为了解决强度问题。</li>
<li><strong>材料。</strong>DOM 钢管是基础配置。铝制传动轴管每英尺更贵，需要专用于铝管的焊接叉，焊接也更讲究；相同长度下请预期明显的加价。<a href="/guides/choosing-driveshaft-tubing">传动轴管指南</a>说明了何时值得选用铝管。</li>
<li><strong>一件式还是两件式。</strong>两件式相当于两根传动轴，外加中间支撑、花键轴和额外的十字轴。它是长轴距的正确解决方案，但价格属于另一个档次。请参阅<a href="/guides/one-piece-vs-two-piece-driveshaft">一件式与两件式</a>。</li>
<li><strong>端部配置。</strong>一端滑动叉、另一端（主动齿轮端）焊接叉是最简单的配置。法兰叉比焊接叉贵；CV 头（双万向节）比两者都贵；在法兰对法兰的传动轴内加装花键滑动组件，价格会再次增加。</li>
<li><strong>长度。</strong>传动轴管按英尺计价，所以 70 英寸的传动轴比 50 英寸的多用一些管材。长度还可能迫使您更换材料或改用两件式，这比管材本身的影响大得多。</li>
</ol>
<p><em>不会</em>改变价格的因素：尺寸本身（在同一根管材的范围内，任何长度的人工都相同）、喷漆和平衡，这些是每根传动轴都有的。</p>

<h2 id="included">报价包含的内容</h2>
<ul class="guide-x">
<li>按您的尺寸切割的 DOM 钢管或 6061 铝管</li>
<li>压入并在工装上焊接的焊接叉，系列按您的选择</li>
<li>两端全新的十字轴（可加注润滑脂或密封型，由您选择）</li>
<li>按规格配置的滑动叉、法兰叉或 CV 头</li>
<li>校直至径向跳动小于 0.010 英寸</li>
<li>在机器上进行高速平衡，并焊接配重块</li>
<li>喷漆及货运包装</li>
</ul>
<p>以下内容除非另行添加，否则不包含：主动齿轮端的端叉或车辆一侧的配对法兰（通常您已有一个）、卡箍或 U 形螺栓套件，以及两件式传动轴中已损坏的中间支撑轴承座。所有这些都可在<a href="/shop/driveshaft-components">部件</a>中找到。</p>

