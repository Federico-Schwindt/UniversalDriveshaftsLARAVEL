<p>传动轴是按某一长度制造的，这个长度一旦错了，其他一切都无从谈起。全国各地的修理厂都用同样的方法、同样的基准点来测量，因为组成传动轴的各个零件（万向节叉、传动轴管、万向节）都是以<strong>万向节十字轴的中心线</strong>和<strong>法兰面</strong>为依据来定义的。把这两个基准弄明白，下面所有的尺寸就自然对得上了。本指南使用的字母与我们的<a href="/driveshaft-designer">传动轴设计器</a>完全一致，所以你可以先画出传动轴，填上数字，然后打印或发送图纸。</p>

<h2 id="refs">基准：A、B、C、W 和 T</h2>
<p>五个字母可以描述任何一根传动轴。单段式传动轴用 C、W 和 T。两段式传动轴再加上 A 和 B，并将前传动轴编号为 1，后传动轴编号为 2。</p>
<div class="dtable-wrap"><table class="dtable">
<thead><tr><th>代号</th><th>含义</th><th>起点</th><th>终点</th></tr></thead>
<tbody>
<tr><td>A</td><td>整套总成的总长度</td><td>前端基准（万向节中心或法兰面）</td><td>后端基准</td></tr>
<tr><td>B1 / B2</td><td>前端到中间支撑；中间支撑到后端</td><td>端部基准</td><td>轴承中心（橡胶减震块的中点）</td></tr>
<tr><td>C1 / C2</td><td>每一节传动轴各自的长度</td><td>万向节中心或法兰面</td><td>该节传动轴另一端的万向节中心或法兰面</td></tr>
<tr><td>W1 / W2</td><td>传动轴管长度，焊缝到焊缝</td><td>前焊缝</td><td>后焊缝</td></tr>
<tr><td>T</td><td>传动轴管外径</td><td colspan="2">用卡尺在管体上测量，避开焊缝和动平衡配重块</td></tr>
</tbody></table></div>
<p>端部基准由两条规则确定。如果该端是<strong>万向节</strong>（滑动叉、端叉、带十字轴的焊接叉），基准就是<strong>十字轴中心</strong>，也就是轴承盖的中心线所在位置。如果该端是<strong>法兰</strong>（法兰叉、等速法兰、配对法兰），基准就是与对应部件用螺栓连接的那个<strong>法兰面</strong>。千万不要量到万向节叉耳的顶端或轴承盖的边缘。</p>

<div class="guide-note"><b>为什么用十字轴中心？</b>目录中的每个万向节叉都是按“中心线到端面”标注尺寸的（例如标为 5.000 CL 到端面的滑动叉，其十字轴距花键端 5 英寸）。当你给我们两个万向节中心之间的长度时，我们会扣除万向节叉的尺寸，然后把传动轴管切到准确长度。</div>

<h2 id="tools">你需要准备什么</h2>
<ul>
<li>一把钢卷尺，或者更好的是一把硬直尺，用于测量所有不足 24 英寸的尺寸。布尺会拉伸。</li>
<li>一把卡尺，用来测量传动轴管直径和花键直径。绕管子一圈量出来的是周长，不是直径。</li>
<li>一支油漆笔或粉笔，在拆卸任何东西之前先标记万向节叉的相位。</li>
<li>如果在车上测量，车辆需处于<strong>行驶高度</strong>，悬架承载。千斤顶支架要放在车桥下面，而不是车架下面。</li>
</ul>

<h2 id="one-piece">如何测量单段式传动轴</h2>
<p>三种情况涵盖了几乎所有单段式传动轴。先确认两端的类型，再进行测量。</p>
<h3>变速箱端为滑动叉，后桥端为端叉或法兰</h3>
<ol class="guide-steps">
<li>将滑动叉推到变速箱输出轴上，直到顶到底。我们的<a href="/online-builder">在线定制传动轴</a>就是按这个长度来计算的：完全压缩状态。</li>
<li>测量 <strong>C</strong>：从前万向节十字轴中心量到后十字轴中心（主动齿轮上是端叉时），或量到后法兰面（主动齿轮上是法兰叉时）。</li>
<li>测量 <strong>W</strong>：沿传动轴管量取焊缝到焊缝的距离。</li>
<li>用卡尺测量 <strong>T</strong>，即传动轴管外径。常见规格为钢管 2.000、2.500、3.000 和 3.500 英寸，铝管 3.500 到 4.000 英寸。</li>
<li>记录滑动叉的花键：数清花键齿数，并用卡尺量出大径。1.250 x 16、1.375 x 16 和 1.500 x 16 涵盖了大多数轻型卡车。</li>
</ol>
<h3>法兰对法兰（没有滑动叉）</h3>
<p>许多进口车、近年的卡车和所有工业传动轴两端都装有用螺栓连接的法兰。滑动行程在传动轴内部（花键滑动总成），或者根本没有。在传动轴装好、车辆处于行驶高度时，测量法兰面到法兰面的 <strong>C</strong>。这里没有压缩或伸长位置需要考虑，但也没有余量：这个数字必须精确到十六分之一英寸。请记下每个法兰的<strong>螺栓孔分布圆直径</strong>、<strong>螺栓孔数量和尺寸</strong>以及<strong>定位止口直径</strong>（用于法兰定心的凸起或凹陷圆环）。<a href="/guides/slip-yoke-vs-weld-yoke-vs-flange-yoke">万向节叉指南</a>讲解了如何识别法兰。</p>
<h3>没有传动轴时如何在车上测量</h3>
<p>当旧传动轴已经不在或者装错了，就直接测量车辆。在悬架承载状态下，从变速箱输出端量到主动齿轮：从输出端万向节叉的十字轴中心量到主动齿轮万向节叉的十字轴中心；如果没有滑动叉，则从油封面量到法兰面。请告诉我们你使用了哪些基准。我们还需要输出轴的花键（齿数和直径），以及主动齿轮万向节叉的系列或法兰孔位图案。</p>

<h2 id="two-piece">如何测量两段式传动轴</h2>
<p>两段式传动轴有一根前传动轴，其末端通过<strong>中间支撑</strong>支承在一根短轴（中间轴）上，另有一根后传动轴套在这根短轴上滑动。轴承支架用螺栓固定在横梁上，所以它的位置由车辆决定。正因为如此，我们需要 B 的两个数值，而不仅仅是总长 A。</p>
<ol class="guide-steps">
<li>标记相位：在两节传动轴之间的花键滑动接头上画一条跨越接头的油漆线，以便后万向节叉回到相同的旋转位置。</li>
<li>在滑动接头处于安装位置时，测量 <strong>A</strong>，即前基准到后基准的距离。</li>
<li>测量 <strong>B1</strong>：从前基准量到中间支撑的中心（橡胶的中点，而不是支架的表面）。测量 <strong>B2</strong>：从轴承中心量到后基准。B1 + B2 应该等于 A；如果不等，请重新测量。</li>
<li>测量 <strong>C1</strong>，即前传动轴，从它的前基准量到其后十字轴的中心（位于轴承后方）；再测量 <strong>C2</strong>，即后传动轴，从同一个十字轴中心量到后基准。</li>
<li>测量 <strong>W1</strong> 和 <strong>W2</strong>，即每根传动轴管的焊缝到焊缝距离，并用卡尺测量每根的 <strong>T</strong>。前后传动轴管的直径往往不一样。</li>
<li>记录短轴的花键（齿数和直径）以及轴承支架的类型。<a href="/guides/center-support-bearing-replacement">中间支撑轴承指南</a>讲解了如何识别。</li>
</ol>
<p>如果你手上只有车辆，请找到轴承横梁，测量变速箱输出端到横梁螺栓孔图案中心的距离作为 B1，再测量从那里到主动齿轮的距离作为 B2。设计器中的<a href="/driveshaft-designer/2">两段式图纸</a>标出了这里的每一项尺寸，避免你漏掉任何一个。</p>

<h2 id="ends">万向节叉、法兰和花键数据</h2>
<p>仅凭长度还不足以确定一根传动轴。每个端部都必须与车辆匹配，所以请在测量的同时收集以下信息：</p>
<div class="dtable-wrap"><table class="dtable">
<thead><tr><th>端部类型</th><th>需要记录的内容</th><th>方法</th></tr></thead>
<tbody>
<tr><td>滑动叉</td><td>花键齿数、大径、万向节系列</td><td>数清花键齿数并用卡尺量齿顶到齿顶；测量万向节轴承盖（<a href="/guides/u-joint-series-identification-chart">系列对照表</a>）</td></tr>
<tr><td>端叉（主动齿轮或分动箱）</td><td>万向节系列、卡环或 U 型螺栓类型</td><td>轴承盖的直径和宽度；记录轴承盖是用卡环、U 型螺栓还是螺栓固定盖板固定</td></tr>
<tr><td>法兰叉</td><td>螺栓孔分布圆、螺栓孔数量和尺寸、定位止口直径、凸止口或凹止口</td><td>测量相对两个螺栓孔的中心距；用卡尺测量止口</td></tr>
