</tbody></table></div>
<p>照片很有帮助。拍一张侧面照片显示整根传动轴，每个端部正面各拍一张，以及传动轴管或万向节叉上任何标签或压印编号的照片。Spicer、Neapco 和原厂传动轴通常带有零件号，我们一看就能知道系列。</p>

<h2 id="mistakes">会导致返工的常见错误</h2>
<ul class="guide-x">
<li><strong>量到万向节叉耳的顶端。</strong>叉耳因系列和制造商而异，而十字轴中心则不会。</li>
<li><strong>在滑动叉处于半伸出状态时测量</strong>却不加说明。这样长度就取决于当天花键恰好停在哪个位置。</li>
<li><strong>车辆停在车架举升机上</strong>，车桥悬空。此时传动轴处于完全伸长状态；而在行驶高度下，由于悬架行程，它会更短。</li>
<li><strong>用周长代替直径。</strong>2.500 的管子绕一圈约 7.85。把 7.85 当作直径给我们，这是明显的错误；而换算出错之后给我们 3.000，就不那么容易被发现了。</li>
<li><strong>忘记相位标记</strong>（两段式传动轴）。传动轴重新装配时相位错开了 180 度，振动却被归咎于新零件。</li>
<li><strong>没有说明万向节系列。</strong>1310 和 1330 的轴承盖直径相同，在一米外看起来完全一样。</li>
</ul>

