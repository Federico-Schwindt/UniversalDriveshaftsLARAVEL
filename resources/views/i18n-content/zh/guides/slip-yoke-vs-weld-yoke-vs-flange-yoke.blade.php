<h2 id="choose">项目选配方法</h2>
<p>当你在<a href="/online-builder">自制传动轴</a>中配置传动轴时,有关万向节叉的问题依次是:变速箱上是什么(滑动叉用的花键,或法兰规格)、主动齿轮轴上是什么(端叉系列,或法兰规格),以及你希望传动轴按哪个系列制造。“自制传动轴”会在每一步提供匹配的万向节叉,并给出报价。三条实用规则:</p>
<ul>
<li>让<strong>每一端的系列与车辆原有的万向节叉一致</strong>,或在一端使用转换万向节。不要两端都尝试转换。</li>
<li>如果车辆是<strong>法兰</strong>式,就保留法兰。把法兰式主动齿轮轴改成叉式,意味着要换新的配对法兰,通常还要换螺母和主动齿轮油封。</li>
<li>对于<strong>加高或大角度</strong>应用,在分动箱一侧装等速头(双万向节),在主动齿轮轴一侧装单万向节;<a href="/guides/driveshaft-angles-and-pinion-angle">角度指南</a>解释了原因。</li>
</ul>
