<h2 id="end">端叉与变速箱叉</h2>
<p>端叉带有花键孔,用螺母固定在轴上:差速器主动齿轮轴(主动齿轮叉)、分动箱输出轴,或不使用滑动叉的变速箱输出轴。它承载万向节的固定一半。选配依据花键齿数和直径、万向节系列以及固定方式:<strong>卡箍式</strong>(两个小卡箍加四颗螺栓)、<strong>U 形螺栓式</strong>(两个带螺母的 U 形螺栓)或<strong>螺栓固定盖板式</strong>(带耳的盖板用螺栓固定在叉上,常见于中型工况)。卡箍或 U 形螺栓套件是单独的小配件,最好与万向节一起更换。端叉见<a href="/shop/driveshaft-components/end-yokes">端叉</a>和<a href="/shop/driveshaft-components/transmission-yokes">变速箱叉</a>。</p>

