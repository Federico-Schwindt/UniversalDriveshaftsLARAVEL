<p>拆开一根传动轴,剩下的是一根传动管,两端各焊接一个万向节叉,每个叉上装一个万向节,把传动轴与车辆连接起来。万向节叉的类型区别在于<strong>它如何与车辆连接</strong>:<em>滑动叉</em>套在花键轴上滑动,<em>法兰叉</em>用螺栓固定在法兰上,<em>端叉</em>用螺母固定在主动齿轮轴或输出轴上,而<em>焊接叉</em>则是焊在传动轴管上的那一半。每种叉的尺寸由<a href="/guides/u-joint-series-identification-chart">万向节系列</a>决定。类型和系列选对了,传动轴就能装得上。</p>

<h2 id="map">各个万向节叉装在哪里</h2>
<p>以一辆典型的后驱皮卡为例,从变速箱向后依次看:</p>
<ol class="guide-steps">
<li><strong>变速箱输出轴</strong>:外部带花键。<strong>滑动叉</strong>套在上面滑动,并带有前万向节。有些车辆的变速箱上装的是用螺栓固定的<strong>端叉</strong>或<strong>法兰</strong>,滑动结构则在传动轴内部。</li>
<li><strong>传动管前端</strong>:焊接一个<strong>焊接叉</strong>(管叉),承载前万向节的另一半。在末端为法兰式的传动轴上,焊接叉连接的是<strong>法兰叉</strong>,而不是滑动叉。</li>
<li><strong>传动管后端</strong>:另一个焊接叉,或者在两段式传动轴上是一根<strong>滑动轴头</strong>。</li>
<li><strong>主动齿轮轴</strong>:<strong>主动齿轮端叉</strong>(卡箍式、U 形螺栓式或螺栓固定盖板式),或者与传动轴法兰叉对接的<strong>配对法兰</strong>。</li>
</ol>
<p>两段式传动轴增加了一根带<strong>中间支撑轴承</strong>的<strong>轴头(中间轴)</strong>,以及后段传动轴上在其上滑动的<strong>滑动叉或花键套</strong>。工业传动轴和取力器传动轴则用键槽轮毂、花键套或快拆式 PTO 叉取代这些万向节叉,但原理完全相同。</p>

<h2 id="slip">滑动叉</h2>
<p>滑动叉是带有一个内部花键长筒的万向节叉。它提供悬架运动时传动系统所需的<strong>长度变化</strong>,也让传动轴可以通过滑动方式拆下。选配时需要四项数据:</p>
<ul>
<li><strong>花键齿数和大径</strong>:1.250 x 16、1.375 x 16、1.500 x 16、1.125 x 27、1.375 x 32 等。必须与输出轴完全一致。</li>
<li><strong>万向节系列</strong>:1310、1330、1350、1410、3R、7290……叉耳只针对单一系列加工。</li>
<li><strong>中心到端部</strong>(CL 到端部):从万向节十字轴中心到筒端的距离。筒越长,行程越大,也能够到缩得很深的后壳体输出口。常见数值有 5.000、5.500、6.000 和 7.375 英寸;<a href="/parts/2-3-1421KX">2-3-1421KX</a> 是 1310 系列、1.250 x 16 花键、CL 到端部为 5 英寸的产品。</li>
<li><strong>油封与堵盖</strong>:大多数在叉耳端部带有堵盖,防止变速箱油漏出;有些是敞口式,用于密封型输出口。防尘罩和防尘套是小配件。</li>
</ul>
<p>滑动叉有两种磨损方式:花键产生旋转间隙,以及长筒外表面在壳体油封接触处磨损,导致漏油。出现任何一种情况都需要更换新的万向节叉。按花键和系列查看<a href="/shop/driveshaft-components/slip-yoke">滑动叉</a>。</p>

<h2 id="weld">焊接叉</h2>
<p>焊接叉(管叉)是传动轴本身的一部分。它有一个加工好的<strong>插入直径</strong>,插入传动轴管内,另有一个台肩供管口顶住,然后围绕焊接。选配依据:</p>
<ul>
<li><strong>传动轴管外径和壁厚</strong>:每种叉都对应一种管规格,例如 2.000 x 0.120 或 3.000 x 0.083。插入直径等于传动轴管的内径(2.000 x 0.120 的管内径为 1.760,所以 <a href="/parts/2-28-1757">2-28-1757</a> 标注的插入直径为 1.766)。</li>
<li><strong>万向节系列</strong>,同上。</li>
<li><strong>中心到焊缝</strong>:从十字轴中心到焊接台肩的距离。这是车间在切管时从你的总长度中扣除的数值。<a href="/parts/2-28-417U">2-28-417</a> 标注的 CL 到焊缝为 1.688。</li>
</ul>
<p>焊接叉是传动轴上最便宜、也最不容易出问题的零件;当叉耳变椭圆、传动轴改换系列或更换传动轴管时才需要更换。可在<a href="/shop/driveshaft-components/weld-yoke">焊接叉</a>中按管规格筛选。如果你在找配套的传动轴管,<a href="/guides/choosing-driveshaft-tubing">传动轴管指南</a>说明了每种叉应搭配多大的管径和壁厚。</p>

