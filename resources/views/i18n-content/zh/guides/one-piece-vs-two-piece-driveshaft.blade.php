<p>长度和转速决定车辆使用单件式还是两件式传动轴。相对于直径而言过长的传动轴管，会在高速公路行驶时就能达到的转速下弯曲并产生甩振；解决办法是改用更大的管、更轻的材料，或者把传动轴一分为二并在中间加以支撑。决策就这么简单。本指南用真实数据逐步讲解，说明两件式传动轴增加了什么（以及什么可能出故障），并介绍两种形式之间的改装。两种传动轴均可在<a href="/online-builder">自配传动轴</a>中按订单制造，两件式传动轴则由我们的车间报价，请<a href="/contact">将尺寸发给我们</a>。</p>

<h2 id="difference">两者的区别</h2>
<p><strong>单件式</strong>传动轴是一根传动轴管，两端各一个万向节叉，配两个万向节。滑动结构通常是变速箱输出端的滑动叉。<strong>两件式</strong>传动轴是两根成一条直线的传动轴管。前段以一根短轴（中间轴）结束，短轴上装有中间支撑轴承，轴承座用螺栓固定在车架横梁上；后段以滑动叉或花键套开始，在这根短轴上滑动，并在后桥主动齿轮端结束。因此，两件式传动轴有三个万向节、一个中间支撑轴承、中间一处精密花键滑动结构，而且前端通常是固定（不滑动）的万向节叉或法兰叉，因为滑动已经在短轴处解决了。</p>

<h2 id="decides">决定因素：长度和转速</h2>
<p>每根传动轴管都有一个临界转速，可用 N<sub>c</sub> = 4,720,000 &times; &radic;(D&sup2; + d&sup2;) / L&sup2; 近似计算（外径、内径和长度均以英寸为单位，结果单位为 RPM）。长度是平方关系，所以起决定作用。车间通常要求传动轴在其可能达到的最高车速下，保持在 N<sub>c</sub> 的 80% 以下。下表列出在两种传动轴转速下，不超出该限值的最长单件式传动轴管：</p>
