<p>多出来的这些部件，就是两件式传动轴价格更高、需要更多关注的原因。它们也是两件式传动轴能够工作的原因：每一段都足够短，可以用较小的传动轴管高速旋转，而中间支撑轴承使万向节夹角保持较小且恒定。出现振动的两件式传动轴，几乎总是轴承、相位或夹角方面的问题；<a href="/guides/center-support-bearing-replacement">中间支撑轴承指南</a>和<a href="/guides/driveshaft-vibration-and-noise-diagnosis">振动诊断指南</a>对这两方面都有介绍。</p>

<h2 id="convert">从两件式改为单件式</h2>
<p>人们改装有三个原因：中间支撑轴承反复损坏；车辆被加高后，两件式传动轴的夹角变得难以控制；或者想减少零件。当总长度（变速箱输出端到主动齿轮，在行驶高度下测量）在上表中单件式传动轴管的能力范围内时，改装是可行的。实际上，这意味着长货箱的单排座皮卡和短货箱的加长驾驶室皮卡，长度在 62 到 70 英寸之间，用 3.500 的钢管或 4.000 的铝管制作。超过约 70 英寸，单件式传动轴就需要一根对传动轴通道来说过大的传动轴管，或者转速上限低于高速公路行驶所需的转速。</p>
<p>改装需要：正确测量的总长度（参见<a href="/guides/how-to-measure-a-driveshaft">测量指南</a>）、用于新滑动叉的变速箱输出花键、主动齿轮万向节叉的系列号或法兰孔型，以及对工作夹角的检查，因为单件式传动轴现在从变速箱到主动齿轮走的是一条直线，可能需要调整主动齿轮的角度。横梁和支架将不再使用。量好数据之后，<a href="/online-builder">单件式「自配传动轴」</a>可以处理订单。</p>
<p>反过来，从单件式改为两件式并不常见，只适用于原车就带有轴承横梁的车辆，通常是原厂配有两件式传动轴的长轴距底盘。</p>

