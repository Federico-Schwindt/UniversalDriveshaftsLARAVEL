<h2 id="identify">如何确定正确的轴承</h2>
<p>中间支撑轴承有几十种规格，每种规格适用于许多车型。请按以下顺序核对这些数据：</p>
<ol class="guide-steps">
<li><strong>内径。</strong>轴承孔要与轴颈的轴承座相匹配。用卡尺测量轴承座，或读取轴承上刻印的直径。常见数值有1.181（30 mm）、1.378（35 mm）、1.574（40 mm）和1.772（45 mm）。例如，<a href="/parts/3R80-50">3R80-50</a>的内径标为1.378，适用于S10、Sonoma和Dakota。</li>
<li><strong>支架类型和螺栓间距。</strong>平板双螺栓卡箍、拱桥式，或具有特定安装尺寸的原厂冲压支架。测量安装孔之间的中心距，并记下孔径。</li>
<li><strong>橡胶外形。</strong>有些是简单的圆环，有些在支架上带有隔套或螺柱（适用于GM皮卡的<a href="/parts/212032-1X">212032-1X</a>带有0.380的隔套螺柱）。橡胶的高度决定传动轴的高度；选错会改变角度。</li>
<li><strong>适用车型。</strong>我们的商品列表标明了常见适用车型。如果旧支架上的原厂编号还看得清，请据此核实。</li>
</ol>
<p>价格并不是衡量质量的可靠标准，但密封轴承加硫化橡胶减震套（而不是仅压入）的产品寿命最长。我们的大多数产品售价在$20到$60之间，配件页面会显示库存。</p>

<h2 id="steps">更换步骤</h2>
<div class="guide-warn"><b>拆卸任何部件之前：</b>在每个要分开的连接处画一道横跨的线，尤其是两段传动轴之间的滑动花键连接，以及后端的法兰或万向节叉。相位很重要，而做标记不花一分钱。</div>
<ol class="guide-steps">
<li><strong>支起车辆</strong>，把支架垫在车桥下方，使悬架处于行驶高度；否则要记住之后需要重新检查角度。变速器挂空挡，松开手刹，用楔块挡住车轮。</li>
<li><strong>拆下后段传动轴</strong>与主动齿轮的连接（卡箍、U形螺栓或法兰螺栓），然后将其从轴颈的花键上滑出。如果也要拆下前段，请接住变速器滑动叉可能漏出的油；大多数作业不需要这样做。</li>
<li><strong>从横梁上拧下支架。</strong>记下所有垫片、隔套或斜垫圈及其朝向。前段此时挂在变速器的万向节叉上。</li>
<li><strong>用压力机压出旧轴承。</strong>如有防尘罩或挡板，请先取下。轴承是压在轴承座上的；用两爪拉马，或用压力机配合内圈后面的开口垫板即可取出。不要用锤子敲击轴颈；后面的滑动花键是经过精密磨削的。</li>
<li><strong>检查轴颈。</strong>查看轴承座是否有划痕，或轴承打转的迹象（表面发蓝或有咬伤）。检查滑动花键是否有锈蚀凹坑或旋转间隙。轴颈损坏就意味着要换新的<a href="/shop/driveshaft-components/stub-midship-shaft">轴颈</a>，这属于车间作业，因为需要拆开万向节，往往还要拆开传动轴管。</li>
<li><strong>压入新轴承</strong>，只推内圈，用一根不接触橡胶的管子顶压，直到轴承贴紧轴肩。压外圈或压支架会在轴承转动一圈之前就将其损坏。装上挡板。</li>
<li><strong>重新装配。</strong>给滑动花键涂脂，将后段传动轴对准相位标记滑入，并拧紧后部的万向节叉或法兰。用原来的垫片把支架固定到横梁上，先不要完全拧紧。</li>
<li><strong>对中并施加扭矩。</strong>在车辆处于行驶高度时，传动轴应位于支架中央，橡胶不应被压向任何一侧。在支架的长孔中调整位置，使其不受预载，然后按规定扭矩拧紧支架螺栓及其他所有螺栓。</li>
</ol>

<h2 id="shim">垫片与对中</h2>
<p>轴承的作用是让轴颈保持在一个高度，使两侧的万向节以较小且相等的角度工作。支架下方的原厂垫片决定这个高度；请把它们装回去。如果车辆被升高或降低、变速器支架塌陷，或新轴承的橡胶高度不同，可能需要校正角度。快速检查方法：轴承拧紧后，用数字倾角仪测量前段和后段的角度。轴承处的万向节应当看到大约1到3度的角度。如果两段几乎平行，万向节的工作角度为零，滚针得不到润滑；如果折角超过约3度，就用垫片降低或升高支架。<a href="/guides/driveshaft-angles-and-pinion-angle">角度指南</a>介绍了完整的步骤。不要为了凑角度而把橡胶向一侧预压；传动轴在减震套中必须处于放松状态。</p>

