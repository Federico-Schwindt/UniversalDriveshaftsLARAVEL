<p>两段式传动轴需要有东西在中间支撑。这就是中间支撑轴承（也叫吊挂轴承）：一个密封的球轴承装在中间轴颈上，悬挂在钢制支架内的橡胶减震套中，支架则用螺栓固定在横梁上。橡胶让传动轴能随底盘一起移动并吸收振动；轴承让传动轴能够旋转。这两样东西都会磨损。本指南介绍如何确认故障、选购正确的配件，以及如何把活干好，避免日后再次出现振动。我们有<a href="/shop/driveshaft-components/center-support-bearing">300多种中间支撑轴承</a>，适用于国产和进口的皮卡、厢式货车和SUV。</p>

<h2 id="what">轴承的作用</h2>
<p>在两段式传动轴中，前段的末端是一根<strong>轴颈</strong>（中间轴）：一根带花键的短轴，上面有轴承座，还有一段滑动花键，后段传动轴就在这段花键上工作。轴承装在轴承座上，紧靠连接两段的万向节前面。它的作用是：把传动系统的中部定位在正确的高度，使两侧万向节的角度符合设计要求；支撑传动轴的重量，防止其甩动；并通过橡胶把传动系统的振动与车身隔离。轴承正常时，你感觉不到它的存在；一旦出问题，就会表现为噪音、下垂或振动。<a href="/guides/one-piece-vs-two-piece-driveshaft">一段式与两段式指南</a>解释了卡车为什么采用这种结构。</p>

