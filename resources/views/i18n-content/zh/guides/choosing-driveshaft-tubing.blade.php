<h2 id="critical">临界转速：公式</h2>
<p>对于两端支撑的中空钢管或铝管，其以 RPM 为单位的第一临界转速可非常精确地近似为：</p>
<div class="guide-formula u-mono">N<sub>c</sub> = 4,720,000 &times; &radic;(D&sup2; + d&sup2;) / L&sup2;</div>
<p>其中 <strong>D</strong> 是传动轴管外径（英寸），<strong>d</strong> 是内径（外径减去两倍壁厚），<strong>L</strong> 是传动轴管长度（英寸）。由此得出三点结论：</p>
<ul>
<li>长度是<strong>平方</strong>关系。长度翻倍会使临界转速降至四分之一。公式中没有任何其他因素能与之相比。</li>
<li>直径的作用大致成正比。将外径从 3.000 增加到 3.500，临界转速会提高约 17%。</li>
<li>壁厚几乎无关紧要。较厚的壁增加了重量和扭矩容量，而不是抗振颤能力；随着 D 保持不变，d 会变小。</li>
</ul>
<p>切勿在临界转速下工作。修理厂在设计传动轴大小时，会将<strong>最高工作转速</strong>（最高档位下的最高发动机转速，包括超速档，如果保守一点可以乘以最终传动比，或者直接按最高公路车速时的传动轴转速计算）保持在 N<sub>c</sub> 的 <strong>75% 到 80%</strong> 以下。传动轴转速等于发动机转速除以该档位的变速箱传动比，在最高档位时，该转速接近发动机转速。</p>
