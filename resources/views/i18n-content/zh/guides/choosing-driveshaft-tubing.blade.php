<p>传动轴管是传动轴中最长、最轻且最常被误解的部件。它的尺寸并非首先由扭矩决定，而是由<strong>转速</strong>决定的。每根传动轴管都有一个旋转速度，在该速度下，它会由于自身的离心载荷开始向外弯曲并产生振颤。这就是<strong>临界转速</strong>，它取决于传动轴管的直径、壁厚，尤其是长度。选择传动轴管的关键在于，在传递扭矩的同时，将其转速保持在该临界转速的安全水平以下，而计算过程只需两分钟。我们<a href="/shop/custom-cut-tubing/tubing">定长切割的 DOM 传动轴管</a>按英尺出售，尺寸如本文所述。</p>

