<p>一辆半吨级皮卡，配备 56 英寸（焊缝到焊缝）的一件式传动轴，采用外径 3.000 &times; 壁厚 0.083 的钢管，在强力加速期间，最高车速为 2,400 RPM，最高档位转速达到 5,500 RPM。</p>
