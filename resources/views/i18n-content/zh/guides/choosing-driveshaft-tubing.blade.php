<h2 id="yokes">如何将传动轴管与焊接叉配合使用</h2>
<p>焊接叉经过机械加工以适应特定的传动轴管尺寸。其<strong>承口直径</strong>等于传动轴管的内径，以便以轻盈的过盈配合滑入，台阶则用于固定焊接位置。3.000 x 0.083 的传动轴管内径为 2.834，并配备标有适用于 3.000 x 0.083 的万向节叉；如果将该万向节叉装入 3.000 x 0.120 的传动轴管（内径 2.760），则无法装入。目录中的每个<a href="/shop/driveshaft-components/weld-yoke">焊接叉</a>都指明了其可接受的传动轴管直径、壁厚以及承口直径，因此一旦选定了传动轴管，您就可以筛选万向节叉。铝管需要铝质焊接叉；钢质万向节叉不能焊接在铝管上。<a href="/guides/slip-yoke-vs-weld-yoke-vs-flange-yoke">万向节叉指南</a>涵盖了关于万向节叉决策的其余部分。</p>

