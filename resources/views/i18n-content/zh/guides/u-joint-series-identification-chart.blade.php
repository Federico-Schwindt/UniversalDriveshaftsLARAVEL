<p>每个万向节都由两个数字确定：<strong>轴承杯直径</strong>和<strong>杯间宽度</strong>，即从卡环槽到卡环槽之间的距离（外卡环式万向节则从卡环到卡环）。系列名称（1310、1350、7290 等）只是这一组尺寸的简称。量一下轴承杯，在下表中查找，就能知道您用的是哪种万向节、哪种万向节叉以及哪个强度等级。我们销售的每个万向节都按系列归类在<a href="/shop/driveshaft-components/u-joints">万向节分类</a>中。</p>

