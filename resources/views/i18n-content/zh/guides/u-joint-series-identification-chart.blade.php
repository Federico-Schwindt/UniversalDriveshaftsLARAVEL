<h2 id="measure">如何测量轴承杯</h2>
<ol class="guide-steps">
<li><strong>轴承杯直径。</strong>万向节从万向节叉上拆下后，用卡尺量一个轴承杯的两侧。如果万向节仍在万向节叉上，则量万向节叉耳孔；标称尺寸相同（1.062、1.078、1.125、1.188 或 1.375）。</li>
<li><strong>宽度。</strong>对于外卡环万向节，从一个卡环槽的<em>内侧面</em>量到对面卡环槽的内侧面；实际操作中，取下卡环后用卡尺量两个轴承杯之间的距离即可。对于内卡环万向节，量两个轴承杯之间的总长，从端到端，因为卡环位于万向节叉耳内侧，基准是轴承杯的两端。</li>
<li><strong>与万向节叉核对。</strong>隔着万向节，从外侧量万向节叉的两个耳。对外卡环万向节，这大约等于宽度减去卡环槽深度；对内卡环万向节，叉耳位于两个轴承杯之间，轴承杯的总长比叉耳间距略大。</li>
</ol>
<div class="guide-note"><b>没有卡尺？</b>1 1/16 英寸的开口扳手可以套进 1.062 的轴承杯，而套在 1.125 的轴承杯上会卡住。这不算测量，但在工作台上可以区分 1310/1330 与 3R/7290。</div>

<h2 id="snap-rings">内卡环还是外卡环</h2>
<p><strong>外卡环</strong>（OSR）万向节在每个轴承杯的开口端附近有一道槽；一个 C 形卡环从万向节叉耳外侧嵌入该槽，将轴承杯固定。Spicer 万向节和大多数轻型皮卡的替换件都是 OSR。<strong>内卡环</strong>（ISR）万向节使用平卡环，装在万向节叉耳上加工出的槽内，位于轴承杯内侧；轴承杯从外侧压入，直到抵住卡环。GM Saginaw（3R/S44）、Chrysler（7260/7290）以及许多进口车万向节都是 ISR。类型不会改变强度，但决定万向节能装进哪种万向节叉：OSR 轴承杯装在 ISR 万向节叉上，就没有任何东西固定它。我们的零件名称在描述中注明了 OSR 或 ISR；例如 <a href="/parts/5-92XU">5-92X</a> 标注为 ISR 型万向节。</p>

<h2 id="grease">可加注润滑脂与免维护</h2>
<p><strong>可加注润滑脂</strong>的万向节在十字轴本体（或轴承杯）上有一个油嘴，每次保养都要加注，加注时会把受污染的润滑脂从油封中挤出。<strong>免维护</strong>（密封、终身润滑）万向节的十字轴是实心的，没有油嘴。由于没有钻孔的油道，同系列的密封十字轴强度更高，因此原厂和竞赛车队多用这种。缺点是，水一旦越过油封就无法排出，万向节只能一直工作到失效。</p>
<ul>
<li><strong>日常使用、拖挂、野外作业、公路冬季撒盐：</strong>可加注润滑脂。每次换机油时一并保养。</li>
<li><strong>赛车、大功率街道用车、任何您不打算维护的场合：</strong>免维护，选用现有最耐用的版本。</li>
<li><strong>涉水越野：</strong>可加注润滑脂，每次涉水后都要排出旧脂并重新加注。</li>
</ul>
<p>同一系列内两种类型的尺寸相同，所以下单时由您选择。如果两种我们都有，零件页面会注明是哪一种；我们的 UDS 品牌万向节带有后缀 <span class="u-mono">U</span>（例如 <a href="/parts/5-1310XU">5-1310XU</a>）。</p>

<h2 id="conversion">转换式万向节</h2>
<p>转换式（组合式）万向节的一根轴上装有一个系列的两个轴承杯，另一根轴上装有另一个系列的两个轴承杯。它可以让某一系列的变速器万向节叉驱动另一系列的传动轴，或把传动轴与原本不匹配的车桥万向节叉连接起来。最常见的有：1310 转 1350、1330 转 1350、1350 转 1410、1410 转 1480，以及 1310 转 3R/S44（我们目录中的 <a href="/parts/5-3022x">5-3022X</a>）。转换式万向节的承载能力取决于较弱的那个系列，对大工作角度的耐受也稍差，所以请把它作为传动轴一端的解决方案，而不要两端都用。</p>

