  <h2>3. 检验、退款与费用</h2>
  <p>退回的商品在收到后将进行检验。经确认属于全新、未安装、完整且可转售的商品，将退款至<b>原始支付方式</b>，扣除 <b>20% 的退货手续费</b>以及原始出库运费（包括我们在包邮促销中补贴的运费），通常在收到货物后 10 个工作日内完成。对于显示有安装痕迹、工具痕迹、油脂、铁锈、缺少五金件或包装损坏的商品，我们有权拒绝接收、自费退还给您或酌情折价退款。通过贸易赊账支付的订单将以账户余额形式退款。我们不承担除零件价格之外的工时费、拖车费、租赁费、停机损失或任何其他费用。</p>

