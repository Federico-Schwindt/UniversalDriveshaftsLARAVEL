  <p>在向您的发卡机构对交易提出争议之前，请先联系我们，我们几乎可以当面解决所有问题。对于已交付的符合要求的商品，或在 RMA 进行期间提出的拒付，我们将凭交付证明和本政策进行抗辩，并可能导致账户暂停以及根据我们的条款追偿相关成本。</p>

