  <p>如果适用旧件押金（core charge），则在收到相同类型且完整、可翻新的旧件后 30 天内予以退还。有裂纹、焊接过、卡死或不完整的旧件不符合退还条件。</p>
  <p><b>换货。</b>若要将库存零件更换为其他零件，请附上您的订单号提交<a href="/exchange-request-form">换货申请</a>；我们将回复 RMA 编号和说明。</p>
