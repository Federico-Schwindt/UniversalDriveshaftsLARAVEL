  <h2>6. 国际运输</h2>
  <p>我们通过 UPS 全球及 DHL 快递进行国际发货，运费在结账时报价，海关文件由我们准备。国际订单以 <b>DAP</b>（目的地交货）方式发货：进口关税、税费、报关行费用以及目的地国家收取的任何费用均不包含在我们的价格中，需由收件人在送货时支付。部分长途或重型物品不能作为包裹进行国际运输；如果您的订单未显示国际运费，请<a href="/contact">联系我们</a>获取货运报价。</p>

