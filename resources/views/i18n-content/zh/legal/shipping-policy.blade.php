  <h2>3. 零担货运（LTL）配送</h2>
  <p>订单包含 <b>5 根或更多传动轴管或整根传动轴</b>、重量达 <b>100 磅或以上</b>，以及任何单件<b>长度超过 108 英寸</b>的商品，都将捆绑在托盘上并通过 LTL 卡车货运发送。同一订单中的其他物品将随该托盘一同运输。货运费在结账时实时计算。</p>
  <ul>
    <li><b>交货地点。</b> 货运费率假定配送至带有装货平台的商业场所。如果配送至住宅，或者现场没有装货平台需要升降机尾板，请在结账时说明，以便运费中包含此项。</li>
    <li><b>收货。</b> 承运商会打电话安排时间。现场必须有人接收。在签收前检查托盘，并在送货单上写下任何可见的损坏。</li>
    <li><b>免运费政策不适用于货运，</b>免运费优惠券也不涵盖货运费用。</li>
  </ul>

