      <h2>Ce que nous faisons</h2>
      <p>Les arbres de transmission sur mesure, en une ou deux pièces, sont fabriqués selon vos dimensions en acier ou en aluminium ; les arbres usés sont reconstruits avec des croisillons, des roulements et du tube neufs ; chaque arbre est redressé et équilibré à vitesse de rotation avant son départ. Si la bonne réponse est une autre série de croisillon ou une autre fourche, nous vous le disons.</p>
      <p>Le <a href="/shop">catalogue</a> réunit des milliers de croisillons, de fourches coulissantes, de fourches à souder, de fourches à bride et de fourches d'extrémité, de paliers centraux et de tube DOM coupé sur mesure, expédiés partout dans le pays depuis le bâtiment même où travaille l'atelier. C'est pourquoi une reconstruction peut être prête dans la même semaine.</p>
