  <ul>
    <li><b>Fréquence des messages :</b> Le nombre de messages peut varier en fonction de vos interactions avec nous.</li>
    <li><b>Frais :</b> Des tarifs de messagerie standard s'appliquent selon votre opérateur de téléphonie mobile.</li>
    <li><b>Désabonnement :</b> Vous pouvez vous désinscrire de la réception de messages SMS à tout moment en envoyant "STOP" par SMS au numéro à partir duquel vous avez reçu le message.</li>
    <li><b>Aide et support :</b> Pour obtenir de l'aide, envoyez "HELP" par SMS à n'importe quel message texte ou contactez-nous directement au (813) 524-6491 ou par courriel à inquiry@universaldriveshafts.com.</li>
