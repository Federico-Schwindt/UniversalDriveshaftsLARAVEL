  <p><b>Politique de confidentialité pour Universal Driveshafts LLC</b><br><span style="color:var(--ink-faint)">Dernière mise à jour : 5 avril 2025</span></p>
  <p>Bienvenue chez Universal Driveshafts LLC. En accédant à nos services ou en les utilisant, y compris en recevant des communications par SMS, vous acceptez la présente Politique de confidentialité. Nous pouvons recueillir votre consentement pour recevoir des messages textuels :</p>
  <ul><li>En soumettant un formulaire en ligne.</li><li>En remplissant un formulaire papier.</li></ul>

  <h2>Types de communications par SMS</h2>
  <p>Si vous avez consenti à recevoir des messages textuels, vous pourriez recevoir des communications par SMS concernant les sujets suivants :</p>
  <ul>
    <li><b>Clients et invités :</b> Mises à jour concernant vos commandes, vos livraisons ou d'autres informations pertinentes.</li>
    <li><b>Candidats à un emploi :</b> Informations sur l'état de votre candidature, documents d'intégration ou autres mises à jour liées à l'emploi.</li>
    <li><b>Rappels de rendez-vous :</b> Rappels importants concernant des services ou des rendez-vous planifiés.</li>
  </ul>
  <p><i>Exemple de message :</i> "Bonjour [Customer Name], ceci est un rappel concernant votre prochain rendez-vous avec Universal Driveshafts LLC le [Date] à [Time]. Nous avons hâte de vous voir ! Pour vous désabonner, répondez 'STOP'."</p>

