      <h2>Lo que hacemos de verdad</h2>
      <p>Ante todo somos un taller de cardanes. Fabricamos cardanes de una y dos piezas a medida, en acero o aluminio; reconstruimos los gastados con crucetas, rodamientos y tubo nuevos; y cada cardán se endereza y se balancea a velocidad antes de salir. Nuestros técnicos diagnostican el problema de la transmisión en vez de venderte piezas por un número de parte, y si la respuesta correcta es otra serie de cruceta u otro yugo, te lo decimos.</p>
      <p>También somos proveedores de repuestos. El <a href="/shop">catálogo</a> reúne miles de crucetas, yugos deslizantes, yugos para soldar, yugos de brida, yugos de extremo, soportes centrales y tubo DOM cortado a medida, organizados por serie y medida y enviados a todo el país desde el mismo edificio donde trabaja el taller. El mecanizado, la soldadura, el armado y el balanceo se hacen junto al inventario, y por eso una reconstrucción puede salir la misma semana en lugar del mismo mes.</p>
