const {chromium}=require(process.env.PWC);
const S=process.argv[2], PW=require('fs').readFileSync(S+'/qa-pw','utf8').trim();
(async()=>{const b=await chromium.launch({executablePath:process.env.BX,args:['--use-fake-ui-for-media-stream','--use-fake-device-for-media-stream','--use-file-for-fake-audio-capture='+S+'/q.wav','--autoplay-policy=no-user-gesture-required']});
const c=await b.newContext({viewport:{width:390,height:844},deviceScaleFactor:2,isMobile:true,hasTouch:true,permissions:['microphone']});const p=await c.newPage();
p.on('console',m=>{if(m.type()==='error')console.log('console:',m.text())});
await p.goto('https://dev.udshafts.com/login',{waitUntil:'load'});
await p.fill('#l-email','qa-shot-temp@example.com');await p.fill('#l-pw',PW);
await Promise.all([p.waitForNavigation({waitUntil:'load'}),p.click('form.authform button[type=submit]')]);
await p.goto('https://dev.udshafts.com/',{waitUntil:'load'});await p.waitForTimeout(1200);
await p.click('.ua-launch');await p.waitForTimeout(1800);
console.log('mic visible',await p.isVisible('[data-ua-mic]'));
await p.click('[data-ua-mic]');await p.waitForTimeout(800);
console.log('rec bar',await p.isVisible('[data-ua-rec]'));
await (await p.$('.ua-panel')).screenshot({path:S+'/v-recording.png'});
await p.waitForTimeout(5200);
const t0=Date.now();
await p.click('[data-ua-rec-send]');
await p.waitForSelector('.ua-row--bot .ua-play',{timeout:120000});
console.log('reply after',(Date.now()-t0)/1000,'s');
await p.waitForTimeout(1500);
console.log('heard:',await p.textContent('.ua-heard'));
console.log('bot:',(await p.textContent('.ua-row--bot .ua-msg')).slice(0,300));
console.log('playing pressed:',await p.getAttribute('.ua-row--bot .ua-play','aria-pressed'));
const src=await p.getAttribute('.ua-row--bot .ua-play','data-src');
const r=await p.evaluate(async s=>{const x=await fetch(s);return [x.status,x.headers.get('content-type'),(await x.arrayBuffer()).byteLength]},src);
console.log('bot audio',src,r);
await (await p.$('.ua-panel')).screenshot({path:S+'/v-reply.png'});
// reload: history shows voice bubble + listen buttons
await p.reload({waitUntil:'load'});await p.waitForTimeout(2500);
console.log('after reload: voice bubbles',await p.$$eval('.ua-msg--me .ua-play',e=>e.length),'listen',await p.$$eval('.ua-msg--bot .ua-play',e=>e.length));
await b.close();})().catch(e=>{console.error(e);process.exit(1)});
