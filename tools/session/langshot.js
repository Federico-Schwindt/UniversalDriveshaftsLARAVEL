// usage: node langshot.js <lang> <outprefix>
const { chromium } = require(process.env.PWC);
(async () => { const [,, lang, out] = process.argv;
  const b = await chromium.launch({ headless: true, executablePath: process.env.BX || undefined, args: ['--no-sandbox'] });
  const d = await b.newPage({ viewport: { width: 1280, height: 800 } });
  d.on('console', m => { if (m.type() === 'error') console.log('console:', m.text().slice(0, 200)); });
  await d.goto('https://dev.udshafts.com/?lang=' + lang, { waitUntil: 'networkidle', timeout: 90000 });
  await d.evaluate(() => document.querySelector('[data-aitr]')?.remove());
  await d.click('.upromo [data-langsw] > summary'); await d.waitForTimeout(400);
  await d.screenshot({ path: out + '-top.png', clip: { x: 640, y: 0, width: 640, height: 330 } });
  await d.keyboard.press('ArrowDown'); await d.keyboard.press('ArrowDown');
  console.log('focused:', await d.evaluate(() => document.activeElement.textContent.trim()));
  await d.keyboard.press('Escape');
  console.log('open after Esc:', await d.evaluate(() => document.querySelector('.upromo [data-langsw]').open));
  const f = await d.$('.langsw--foot'); await f.scrollIntoViewIfNeeded();
  await d.click('.langsw--foot > summary'); await d.waitForTimeout(400);
  const bb = await f.boundingBox();
  await d.screenshot({ path: out + '-foot.png', clip: { x: Math.max(0, bb.x - 300), y: bb.y - 300, width: 760, height: 360 } });
  await d.mouse.click(5, 300);
  console.log('foot open after outside click:', await d.evaluate(() => document.querySelector('.langsw--foot').open));
  const m = await b.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  await m.goto('https://dev.udshafts.com/shop?lang=' + lang, { waitUntil: 'networkidle', timeout: 90000 });
  await m.evaluate(() => document.querySelector('[data-aitr]')?.remove());
  await m.click('.uhead__burger, [data-drawer-open], .uburger').catch(e => console.log('burger', e.message.slice(0, 80)));
  await m.waitForTimeout(500);
  await m.click('.langsw--drawer > summary'); await m.waitForTimeout(300);
  const dd = await m.$('.langsw--drawer'); await dd.scrollIntoViewIfNeeded();
  await m.screenshot({ path: out + '-drawer.png' });
  await m.screenshot({ path: out + '-mobile-shop.png', fullPage: false });
  await b.close(); })();
